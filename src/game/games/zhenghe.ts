function judge(s: Stats) {
  const { 威望, 船力, 邦交, 忠 } = s;

  // 殁于归途:船力耗尽,埋骨绝海(优先级最高)
  if (船力 <= 16) {
    return {
      title: "殁于归途",
      verse: "巨舶飘零浪打舷，孤帆万里水连天。\n三宝旌节沉沧海，魂逐归潮不到边。",
    };
  }

  // 四海宾服:威望、邦交俱卓绝,万国来朝
  if (威望 >= 82 && 邦交 >= 40) {
    return {
      title: "四海宾服",
      verse: "宝船九桅压海来，麒麟献瑞动天阶。\n三十番邦皆稽首，从此沧溟有汉旆。",
    };
  }

  // 怀远柔夷:邦交极厚,以德化远人
  if (邦交 >= 55) {
    return {
      title: "怀远柔夷",
      verse: "不取寸土通万国，瓷帛香珠易远情。\n排栅立城安旧港，海天处处沐皇明。",
    };
  }

  // 宝船永镇:威望显赫,旌节远播极西
  if (威望 >= 75 && 忠 >= 55) {
    return {
      title: "宝船永镇",
      verse: "刻石西洋十万里，碑文犹照月明中。\n忽鲁谟斯麒麟至，永示万年天朝功。",
    };
  }

  // 宣德遗烈:忠勤始终,功成身殁于海
  if (忠 >= 78) {
    return {
      title: "宣德遗烈",
      verse: "七奉皇华鬓已霜，古里涛声送归航。\n一生尽付沧溟阔，牛首山高葬海郎。",
    };
  }

  // 海禁孤舟:威望、邦交俱衰,盛事难继
  if (威望 < 50 && 邦交 < 30) {
    return {
      title: "海禁孤舟",
      verse: "巍巍宝舶化尘烟，针路图残封禁严。\n空忆当年帆似雪，西洋一去渺无船。",
    };
  }

  // 兜底:三宝遗踪
  return {
    title: "三宝遗踪",
    verse: "曾将旌节遍南溟，番贡梯航次第倾。\n纵未全功亦壮举，海天犹记五更星。",
  };
}


// —— 结局加权裁定:四维定调,给一段婉约苍凉的收束 ——
function judge(s: Stats) {
  const { 才情, 情缘, 家国, 风骨 } = s;
  const sum = 才情 + 情缘 + 家国 + 风骨;

  // 四维俱高:千古第一才女
  if (才情 >= 82 && 风骨 >= 70 && 家国 >= 60) {
    return {
      title: "千古第一才女",
      verse:
        "词压江南,文盖塞北,生当人杰,死亦鬼雄。这世间的女子里,再无第二个你。",
    };
  }
  // 才情独尊:漱玉遗音
  if (才情 >= 82 && 才情 >= 风骨 && 才情 >= 情缘) {
    return {
      title: "漱玉遗音",
      verse:
        "绿肥红瘦,人比黄花,寻寻觅觅一阕《声声慢》。你以一管柔笔,写尽了天下女子说不出的心事。漱玉一卷,千载犹清。",
    };
  }
  // 风骨独高:人比黄花
  if (风骨 >= 76 && 风骨 >= 才情) {
    return {
      title: "人比黄花",
      verse:
        "宁可坐牢,不肯苟全;任世人议你晚节,你只守一身孤介。莫道不销魂,帘卷西风,人比黄花瘦——瘦的是身,硬的是骨。",
    };
  }
  // 情缘为主,且不低:金石永驻
  if (情缘 >= 58 && 情缘 >= 风骨) {
    return {
      title: "金石永驻",
      verse:
        "赌书泼茶,共校金石,二十八载琴瑟相和。纵阴阳两隔,你终把他未竟的《金石录》校成献世。情缘虽断,此义长存。",
    };
  }
  // 家国深重:载不动愁
  if (家国 >= 66 && 家国 >= 情缘) {
    return {
      title: "载不动愁",
      verse:
        "靖康一变,半生收藏付与兵火;载书南奔,只恐双溪舴艋舟,载不动、许多愁。物是人非事事休,欲语泪先流。",
    };
  }
  // 综合不俗:易安居士
  if (sum >= 230) {
    return {
      title: "易安居士",
      verse:
        "归来堂里求一个室陋心安,临安灯下守一段孤寂残年。你这一生,聚散悲欢,何其多也——而终究,以「易安」二字自处。",
    };
  }
  // 兜底:物是人非
  return {
    title: "物是人非",
    verse:
      "风住尘香花已尽,日晚倦梳头。物是人非事事休,欲语泪先流。半世飘零,一川烟雨,都付与这一声叹息了。",
  };
}


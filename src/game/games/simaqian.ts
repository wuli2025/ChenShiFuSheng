// ── 结局加权裁定 ────────────────────────────────────────────
// 呼应「人固有一死,或重于泰山,或轻于鸿毛」。title 4 字内。
function judge(s: Stats) {
  const 史识 = s.史识 ?? 0;
  const 气节 = s.气节 ?? 0;
  const 忍辱 = s.忍辱 ?? 0;
  const 著述 = s.著述 ?? 0;

  // 1) 死节而书未竟:气节极高、著述偏低 —— 重于泰山(以死全节)
  if (气节 >= 60 && 著述 < 35) {
    return {
      title: "重于泰山",
      verse:
        "你择死如归,血荐青史，节烈昭昭。\n" +
        "然十表八书,世家列传,终随你埋于黄土。\n" +
        "后人哀其节,亦惜其书——死有重于泰山者,君是也。",
    };
  }

  // 2) 著述与史识俱卓、忍辱亦深:史家绝唱 —— 最高成就
  if (著述 >= 70 && 史识 >= 65 && 忍辱 >= 45) {
    return {
      title: "史家绝唱",
      verse:
        "幽于缧绁,刑余偷生,而成百三十篇。\n" +
        "究天人之际,通古今之变,成一家之言。\n" +
        "史家之绝唱,无韵之离骚——藏之名山,传之其人。",
    };
  }

  // 3) 忍辱与著述双高,但史识未臻其极:无韵离骚 —— 发愤之书成
  if (忍辱 >= 55 && 著述 >= 55) {
    return {
      title: "无韵离骚",
      verse:
        "肠一日而九回,汗发背而沾衣,君隐忍以终其书。\n" +
        "意有所郁结,故述往事而思来者。\n" +
        "其文如泣如诉,信乎无韵之离骚也。",
    };
  }

  // 4) 史识极高、笔法究极:究天人之际 —— 思想之达
  if (史识 >= 70 && 著述 >= 45) {
    return {
      title: "究天人际",
      verse:
        "网罗天下放失旧闻,考之行事,稽其成败兴坏之纪。\n" +
        "上明三王之道,下辨人事之纪,别嫌疑,明是非。\n" +
        "君之识,通乎天人;君之笔,亘乎古今。",
    };
  }

  // 5) 气节既失、著述亦平:轻于鸿毛 —— 苟全而无所成
  if (气节 < 25 && 著述 < 45) {
    return {
      title: "轻于鸿毛",
      verse:
        "君违心以全身,曲笔以求安,脊骨既折,文采不彰。\n" +
        "九牛亡一毛,与蝼蚁何异。\n" +
        "死有轻于鸿毛者——用之所趋异也,可不慎欤。",
    };
  }

  // 6) 著述尚成、史笔有所回护:藏之名山 —— 书传而未极
  if (著述 >= 45) {
    return {
      title: "藏之名山",
      verse:
        "君以残生易一书,虽有所讳,然百三十篇终成。\n" +
        "正本藏之名山,副在京师,以俟后世知音。\n" +
        "是非乃定,自有来者论之。",
    };
  }

  // 兜底:浮沉于世,书未大成、节未大彰
  return {
    title: "太史浮沉",
    verse:
      "君历宦海风波,负父之命而终未尽偿。\n" +
      "或失之于节,或歉之于书,徘徊于死生之际。\n" +
      "黄河东去,昼夜不息,而君之心事，史阙其文。",
  };
}


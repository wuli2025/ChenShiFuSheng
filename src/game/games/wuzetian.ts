// ───────────────────────── 结局加权裁定 ─────────────────────────
function judge(s: Stats) {
  const { 权术, 世家, 佛道, 民心 } = s;

  // 速亡之局:四方失衡过甚,任一过低皆招祸患(钢丝跌落)。
  if (权术 < 18) {
    return {
      title: "牝鸡司晨",
      verse:
        "权柄不固,大政旁落;一朝政变起,凤冠化作飞灰。\n你输的不是天下,是那双始终不敢够狠的手。",
    };
  }
  if (世家 < 14 && 民心 < 24) {
    return {
      title: "孤家寡人",
      verse:
        "门阀尽寒,黎庶皆怨;铜匦告密,血流神都。\n你坐稳了龙椅,却坐空了人心,孤峰之上,唯余风声。",
    };
  }

  // 高位结局:登顶且四方各有偏重。
  if (权术 >= 60 && 佛道 >= 45 && 权术 >= 民心) {
    return {
      title: "日月当空",
      verse:
        "符瑞自洛水中来,弥勒于僧口里生;\n你以一字为名,日月凌空,照见了一个前无古人的女皇之朝。",
    };
  }
  if (民心 >= 55 && 权术 >= 45) {
    return {
      title: "贞观遗风",
      verse:
        "劝农桑,薄赋徭,广开制举取寒门;\n上承贞观,下启开元,世人终于说:她到底,是治世之君。",
    };
  }
  if (世家 >= 50 && 权术 >= 45) {
    return {
      title: "垂帘称制",
      verse:
        "二圣并坐,帘影沉沉;你不必夺那个名,天下早已尽在帘后。\n调和鼎鼐,与士大夫共天下,亦是一种登顶。",
    };
  }
  if (权术 >= 55 && 民心 < 40) {
    return {
      title: "酷吏之朝",
      verse:
        "周兴来俊臣,请君入瓮;告密成风,株连盈狱。\n你以铁腕坐稳了江山,史笔却为你蘸满了朱砂。",
    };
  }

  // 兜底:走完了钢丝,功过皆付那通无字之碑。
  return {
    title: "无字之碑",
    verse:
      "你从才人走到女皇,又从女皇退回皇后,合葬乾陵。\n碑上不著一字——是非功罪,留与千秋万岁,各自评说。",
  };
}


function judge(s: Stats): { title: string; verse: string } {
  const { 势力, 武略, 民心, 猜忌 } = s;
  const sum = 势力 + 武略 + 民心;

  // 自高门槛向低门槛逐级落子;「猜忌」高则坠入黑暗结局。

  // 黑暗结局:猜忌极高,屠戮功臣,刻薄寡恩
  if (猜忌 >= 60) {
    return {
      title: "火烧功臣",
      verse: "庆功楼火,照尽淮西旧勋之骨。\n孤家寡人坐拥江山,身后唯余猜雄之名。",
    };
  }
  // 准黑暗:猜忌偏高且民心受损,猛政立国而失人和
  if (猜忌 >= 42 && 民心 < 55) {
    return {
      title: "暴秦之续",
      verse: "剥皮实草,大狱连兴,刑名峻急如秦。\n海内虽定,而恩义已薄,后世讥其寡恩。",
    };
  }
  // 最高荣光:势力武略民心俱盛,且猜忌克制
  if (势力 >= 72 && 武略 >= 65 && 民心 >= 65 && 猜忌 < 40 && sum >= 215) {
    return {
      title: "洪武开国",
      verse: "提三尺剑,削平群雄,驱逐胡元。\n布衣而有天下,得国之正,无出其右。",
    };
  }
  // 民族功业:民心武略高,光复中华为第一义
  if (民心 >= 65 && 武略 >= 55) {
    return {
      title: "驱逐胡虏",
      verse: "恢复中华,衣冠重归于故都。\n四百年膻腥一洗,功在社稷,泽被苍生。",
    };
  }
  // 草根本色:民心极高而猜忌甚低,不忘布衣之情
  if (民心 >= 70 && 猜忌 < 30) {
    return {
      title: "布衣天子",
      verse: "放牛乞食起淮西,未改赤子之心。\n与功臣共富贵,以仁厚传于子孙。",
    };
  }
  // 武功偏胜:势力武略足而民心稍逊,马上得之
  if (势力 >= 60 && 武略 >= 55) {
    return {
      title: "马上得国",
      verse: "鄱阳焚舰,平江困城,北逐元主。\n戎马半生而成帝业,武略冠绝一时。",
    };
  }
  // 兜底:乱世挣扎,未能竟功,殁于沟壑
  return {
    title: "殁于沟壑",
    verse: "淮右饥荒,孤身游食于风雨之中。\n时也命也,英雄未及拔剑,已委身于荒草。",
  };
}


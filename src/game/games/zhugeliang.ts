// —— 结局加权裁定:四维定调,给一段悲壮收束。判断由特殊到一般 ——
function judge(s: Stats) {
  const { 治国, 兵略, 民望, 汉室 } = s;
  const sum = 治国 + 兵略 + 民望 + 汉室;

  // 鞠躬尽瘁:四维俱高,德能两全,虽未竟而无憾
  if (汉室 >= 84 && 治国 >= 78 && 民望 >= 66) {
    return {
      title: "鞠躬尽瘁",
      verse:
        "你以一州之疲,抗九州之强;明知大势难回,仍竭尽股肱,死而后已。\n中原未复,而忠贞之节,昭昭如日月,千载之下,犹令英雄堕泪。",
    };
  }
  // 出师未捷:汉室之志极盛而力有未逮,北伐终成绝唱
  if (汉室 >= 82 && 兵略 >= 60) {
    return {
      title: "出师未捷",
      verse:
        "六出祁山,五丈秋风,星陨之夜,壮志未酬。\n出师未捷身先死,长使英雄泪满襟——你输给了天时,却赢得了千秋。",
    };
  }
  // 星落五丈:志气磨折、兵略受挫,然鞠躬之心不改
  if (兵略 < 52 && 汉室 >= 64) {
    return {
      title: "星落五丈",
      verse:
        "街亭之失,夷陵之痛,皆成你案头未干的墨。\n大星西坠,渭水东流;你把未竟的棋局,留给了后来人。",
    };
  }
  // 治世能臣:治国民望俱盛,蜀地大治,而北图未遂
  if (治国 >= 80 && 民望 >= 70) {
    return {
      title: "治世良相",
      verse:
        "你科教严明,赏罚必信,使蜀土路不拾遗、强不侵弱。\n虽未能提兵定中原,却以一身,撑起了一个王朝的清明与体面。",
    };
  }
  // 偏安守成:汉室之志渐消,然守得一方安稳
  if (汉室 < 64 && 治国 >= 66) {
    return {
      title: "三分守成",
      verse:
        "你终究守住了天府之土,保得益州十年无虞。\n只是隆中那卷地图上的中原,渐渐成了灯下一声叹息。",
    };
  }
  // 综合可观的进取者:殚精竭虑,功业斐然
  if (sum >= 260) {
    return {
      title: "卧龙经纶",
      verse:
        "出庐二十七载,你以经天纬地之才,成三分鼎足之业。\n纵使天命难违,这一局棋,你已落子无悔。",
    };
  }
  // 兜底:知其不可
  return {
    title: "知其不可",
    verse:
      "明知汉祚将终,你仍年年北望,岁岁出师。\n成败利钝,非你所能逆睹;鞠躬尽瘁四字,已是你给天下最后的答卷。",
  };
}


// ───────────────────────── 结局加权裁定 ─────────────────────────
// 天命过低则速亡:纵有万里江山,亦不过传之一世而崩。
function judge(s: Stats) {
  const { 国力, 军势, 法度, 天命 } = s;

  // 速亡之局:天命枯竭,民怨累积之结账——焚书坑儒、严刑峻法的延迟兑现在此索命。
  if (天命 < 20) {
    return {
      title: "二世而亡",
      verse:
        "你以为筑起的是万世之基,却原是一座架在民怨之上的危楼。\n沙丘尸骨未寒,赵高指鹿,陈胜揭竿;十五年,大厦倾于一旦。",
    };
  }
  if (天命 < 32 && 法度 >= 55) {
    return {
      title: "焚书之祸",
      verse:
        "诗书既焚,术士既坑,天下读书人之心,尽成秦敌。\n以法为教者,法在而人心已去;骊山烈火未熄,阿房一炬成灰。",
    };
  }
  if (国力 < 24 && 军势 >= 50) {
    return {
      title: "竭泽之业",
      verse:
        "长城横亘万里,驰道直贯九州,皆以黔首白骨为基。\n戍卒呼于陇亩,天下哗然而应;劳民之伤,终成倾国之祸。",
    };
  }

  // 高位结局:四维充盈,各有偏重。
  if (天命 >= 55 && 国力 >= 55 && 法度 >= 50) {
    return {
      title: "万世之基",
      verse:
        "扶苏既立,仁主承统;严法之中,佐以宽和,黔首得以喘息。\n车同轨,书同文,郡县之制传于千秋——你为华夏,真正立起了一根脊梁。",
    };
  }
  if (法度 >= 60 && 国力 >= 50) {
    return {
      title: "书同文轨",
      verse:
        "六合既一,法度衡石、车轨文字,皆出于一。\n纵后世王朝更迭,这「大一统」三字,自你之手,镌入了诸夏的骨血。",
    };
  }
  if (军势 >= 60 && 天命 >= 40) {
    return {
      title: "千古一帝",
      verse:
        "奋六世之余烈,振长策而御宇内,吞二周而亡诸侯。\n北筑长城,南取百越,履至尊而制六合——功盖三皇,德兼五帝,旷古一人。",
    };
  }

  // 兜底:功业既成而虚耗于方士,长生终不可得。
  return {
    title: "求仙不死",
    verse:
      "你据有六合,却求那海上虚无缥缈的蓬莱;\n童男女入海不返,神药终不至。能令山河俯首者,亦不能令鬓边一茎白发回黑。",
  };
}


// —— 结局加权裁定:四维定调,给一段有东坡气韵的收束 ——
function judge(s: Stats) {
  const { 才情, 仕途, 风骨, 旷达 } = s;
  const sum = 才情 + 仕途 + 风骨 + 旷达;

  // 四维俱高:千古一人
  if (才情 >= 80 && 旷达 >= 78 && 风骨 >= 70) {
    return {
      title: "千古一人",
      verse:
        "诗、词、文、书、画,无一不冠绝当世;九死南荒而吟啸自若。后世千年,谈起那个最可爱的中国人,人人都先想起你。",
    };
  }
  // 旷达为尊:一蓑烟雨
  if (旷达 >= 78 && 旷达 >= 才情 && 旷达 >= 风骨) {
    return {
      title: "一蓑烟雨",
      verse:
        "竹杖芒鞋,你走遍贬谪的山河,把每一处瘴海都活成了故乡。回首萧瑟,你只轻轻一句:也无风雨,也无晴。",
    };
  }
  // 才情为尊:文章太守
  if (才情 >= 80 && 才情 >= 风骨) {
    return {
      title: "文章太守",
      verse:
        "大江东去,赤壁两赋,中秋一阕婵娟——你以一支笔,替天地立言,替千载之下的失意人,说出了说不出的话。",
    };
  }
  // 风骨为尊、仕途偃蹇:庙堂孤臣
  if (风骨 >= 76 && 仕途 < 50) {
    return {
      title: "庙堂孤臣",
      verse:
        "新党恨你,旧党亦嫌你,你那一肚皮的不合时宜,从来只装得下是非,装不下逢迎。庙堂虽远,直道在心。",
    };
  }
  // 风骨与旷达兼具:江海余生
  if (风骨 >= 66 && 旷达 >= 64) {
    return {
      title: "江海寄余生",
      verse:
        "小舟从此逝,江海寄余生。你早把功名利禄看作过眼烟云,唯留一江明月、半壶清酒,与天地相对。",
    };
  }
  // 仕途偏高:循吏遗爱
  if (仕途 >= 62 && 仕途 >= 风骨) {
    return {
      title: "循吏遗爱",
      verse:
        "西湖有堤,儋州有学,惠州有桥。你或许未能位极人臣,却把恩泽留在了一处处任所,百姓岁岁立祠,呼你一声「苏公」。",
    };
  }
  // 综合不俗:此心安处
  if (sum >= 230) {
    return {
      title: "此心安处",
      verse:
        "试问岭南应不好?却道:此心安处是吾乡。半生飘零,你终究把漂泊,过成了从容。",
    };
  }
  // 兜底:浮生若寄
  return {
    title: "浮生若寄",
    verse:
      "人生到处知何似?应似飞鸿踏雪泥。一蓑烟雨任平生,潇潇半世,如今俱付与了这江上清风、山间明月。",
  };
}


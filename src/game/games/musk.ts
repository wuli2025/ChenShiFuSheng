// —— 结局加权裁定:四维定调,给一段收束 ——
function judge(s: Stats) {
  const { 资本, 技术, 远见, 意志 } = s;
  const sum = 资本 + 技术 + 远见 + 意志;

  // 见好就收路线:资本高而意志/远见冷
  if (资本 >= 70 && 意志 < 54) {
    return {
      title: "硅谷富豪",
      verse:
        "你赢得了无数人梦寐以求的体面与自由。只是偶尔夜深,你会想:那张纸上的'太空'二字,本可以亲手划掉。",
    };
  }
  // 全面登顶:钢铁纪元
  if (意志 >= 78 && 远见 >= 76 && 技术 >= 66) {
    return {
      title: "钢铁纪元",
      verse:
        "火箭能回收,汽车会开向旷野,屋顶在发电。世人叫你钢铁侠,你只当这是又一个还没做完的清单。从这里起,星辰才刚刚铺开。",
    };
  }
  // 技术+远见:火星之门
  if (技术 >= 72 && 远见 >= 70 && 技术 >= 资本) {
    return {
      title: "火星之门",
      verse:
        "当第一枚火箭稳稳落回地面,你知道那扇门已经推开了。让人类成为跨行星物种——这件事,你这一生不会停手。",
    };
  }
  // 资本+远见:电动黎明
  if (资本 >= 64 && 远见 >= 64) {
    return {
      title: "电动黎明",
      verse:
        "你把'电动车'三个字,从笑话改写成了潮水的方向。超级工厂的灯,会在世界各地一盏盏亮起来。",
    };
  }
  // 意志极高、资本不丰:孤勇者
  if (意志 >= 78 && 资本 < 60) {
    return {
      title: "孤勇者",
      verse:
        "你几乎赔光了一切,却把两家'必死'的公司一起拽出了深渊。钱可以再赚,这种把后背交给悬崖的勇气,世上没几个人有。",
    };
  }
  // 综合不俗的进取者
  if (sum >= 240) {
    return {
      title: "造物者",
      verse:
        "你不只想拥有世界,你想亲手造一个更好的。钟声落下,新的工地才刚刚动土。",
    };
  }
  // 兜底:追光者
  return {
    title: "追光者",
    verse:
      "二十七年,从比勒陀利亚的旧电脑,到纳斯达克的钟声。路是一步一步踩出来的,回头看,每一次坠海都没有白费。",
  };
}


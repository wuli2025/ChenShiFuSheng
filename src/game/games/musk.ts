function recommend(caps: Stats, _stats: Stats): string {
  const keys = Object.keys(caps);
  if (keys.length === 0) return "";
  let top = keys[0];
  let low = keys[0];
  for (const k of keys) {
    if ((caps[k] ?? 0) > (caps[top] ?? 0)) top = k;
    if ((caps[k] ?? 0) < (caps[low] ?? 0)) low = k;
  }
  const fixHint: Record<string, string> = {
    远见: "你太容易被眼前的窗口牵着走——下一步该练的是『远见』,看得再远一点。",
    胆识: "你算得太清、下注太轻——下一步该补的是『胆识』,有些事不赌就永远不会发生。",
    资本运作: "你只顾埋头造东西,却常被钱卡住喉咙——下一步该补的是『资本运作』。",
    工程钻研: "你站得高、看得远,却离螺丝钉太远——下一步该补的是『工程钻研』,亲手把它拆开。",
    用人: "你什么都自己扛——下一步该补的是『用人』,你太习惯亲力亲为。",
    抗压: "顺风时你很猛,逆风时易崩——下一步该练的是『抗压』,熬过至暗的那几夜。",
  };
  const topLabel = top;
  const fix = fixHint[low] || `下一步该补的是『${low}』。`;
  return `你的决策画像偏『${topLabel}』,适合从0到1的硬科技豪赌;${fix}`;
}

